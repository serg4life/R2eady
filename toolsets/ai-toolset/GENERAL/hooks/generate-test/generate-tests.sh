# Main execution
main() {
  log "INFO" "=== Test Generation Hook Started ==="
  
  # Create output directory
  mkdir -p "${OUTPUT_DIR}"
  
  # Get changed files
  changed_files=$(get_changed_files)
  
  if [[ -z "${changed_files}" ]]; then
    log "INFO" "No changed files detected"
    echo "✓ No changes to analyze"
    exit 0
  fi
  
  # Count statistics
  local total_files=0
  local generated_tests=0
  local skipped_files=0
  
  # Process each changed file
  while IFS= read -r changed_file; do
    ((total_files++))
    
    # Skip certain directories/patterns
    if [[ "${changed_file}" =~ tests/|spec/|.*\.test\.|.*_test\. ]]; then
      log "INFO" "Skipping test file: ${changed_file}"
      ((skipped_files++))
      continue
    fi
    
    # Detect language
    local language=$(detect_language "${changed_file}")
    
    if [[ "${language}" == "unknown" ]]; then
      log "INFO" "Skipping unsupported file type: ${changed_file}"
      ((skipped_files++))
      continue
    fi
    
    # Generate test filename
    local test_file=$(get_test_filename "${changed_file}" "${language}")
    
    if [[ -z "${test_file}" ]]; then
      log "ERROR" "Could not generate test filename for: ${changed_file}"
      ((skipped_files++))
      continue
    fi
    
    # Generate test template
    if [[ "${PREVIEW_MODE}" == "true" ]]; then
      log "INFO" "PREVIEW: Would generate test for ${changed_file} -> ${test_file}"
      echo "  → Would create: ${test_file}"
    else
      generate_test_template "${changed_file}" "${language}" "${test_file}"
      log "INFO" "Generated test file: ${test_file}"
      echo "  ✓ Generated: ${test_file}"
      ((generated_tests++))
    fi
  done <<< "${changed_files}"
  
  # Summary
  log "INFO" "=== Test Generation Complete ==="
  log "INFO" "Total files analyzed: ${total_files}, Generated: ${generated_tests}, Skipped: ${skipped_files}"
  
  echo ""
  echo "📊 Summary:"
  echo "   Files analyzed: ${total_files}"
  echo "   Tests generated: ${generated_tests}"
  echo "   Files skipped: ${skipped_files}"
  
  if [[ "${PREVIEW_MODE}" == "true" ]]; then
    echo ""
    echo "⚠️  PREVIEW MODE - No files were actually created"
  else
    echo ""
    echo "✅ Test generation complete. Review and enhance generated tests:"
    echo "   ${OUTPUT_DIR}/"
  fi
  
  exit 0
}

main "$@"
