#!/bin/bash

# Generate unit tests based on git diff
# This script analyzes changed files and generates corresponding unit tests

set -euo pipefail

# Configuration
SKIP_TEST_GENERATION="${SKIP_TEST_GENERATION:-false}"
PREVIEW_MODE="${PREVIEW_MODE:-false}"
ANALYZE_DIFF="${ANALYZE_DIFF:-true}"
OUTPUT_DIR="${OUTPUT_DIR:-tests/generated}"
LOG_LEVEL="${LOG_LEVEL:-INFO}"
COVERAGE_THRESHOLD="${COVERAGE_THRESHOLD:-80}"
TEST_LANGUAGE="${TEST_LANGUAGE:-}"

# Skip if disabled
if [[ "${SKIP_TEST_GENERATION}" == "true" ]]; then
  exit 0
fi

# Create logs directory
mkdir -p logs/copilot

# Logging function
log() {
  local level="$1"
  shift
  local message="$*"
  local timestamp=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
  
  if [[ "${LOG_LEVEL}" != "ERROR" ]] || [[ "${level}" == "ERROR" ]]; then
    echo "[${timestamp}] [${level}] ${message}" >> logs/copilot/generation.log
  fi
}

# Detect language from file extension
detect_language() {
  local file="$1"
  case "${file}" in
    *.py) echo "python" ;;
    *.js|*.ts|*.jsx|*.tsx) echo "javascript" ;;
    *.cc|*.cpp|*.cxx|*.h|*.hpp) echo "cpp" ;;
    *) echo "unknown" ;;
  esac
}

# Get changed files
get_changed_files() {
  local files
  
  # Get both staged and unstaged changes
  files=$(git diff --name-only --cached)
  files+=$(printf '\n'; git diff --name-only)
  
  # Remove duplicates and filter out deleted files
  echo "${files}" | sort -u | while read -r file; do
    if [[ -f "${file}" ]]; then
      echo "${file}"
    fi
  done
}

# Generate test file name based on source file
get_test_filename() {
  local source_file="$1"
  local language="$2"
  local filename=$(basename "${source_file}")
  local name="${filename%.*}"
  
  case "${language}" in
    python)
      echo "${OUTPUT_DIR}/test_${name}.py"
      ;;
    javascript)
      echo "${OUTPUT_DIR}/${name}.test.js"
      ;;
    cpp)
      echo "${OUTPUT_DIR}/${name}_test.cc"
      ;;
    *)
      echo ""
      ;;
  esac
}

